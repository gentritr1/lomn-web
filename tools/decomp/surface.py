"""Platform surface inventory -> docs/surface.md: every PE import + every COM vtable slot the game calls.

Inputs: the exe (imports via nb11.Nb11.imports()), vtable_uses.jsonl, functions.jsonl, d3d8_vtables.txt.
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path


def load_vtables(path: Path) -> dict[str, dict[str, int]]:
    out, cur = {}, None
    for line in path.read_text().splitlines():
        p = line.split(" ")
        if p[0] == "I":
            cur = out.setdefault(p[1], {})
        elif p[0] == "m":
            cur[p[2]] = int(p[1])
    return out


def render(imports: dict[str, list[str]], uses: list[dict], names: dict[str, str], vtables: dict) -> str:
    out = ["# Platform surface (generated by tools/decomp/surface.py)", "",
           f"## PE imports: {len(imports)} DLLs, {sum(len(v) for v in imports.values())} functions", "",
           "| DLL | Count | Functions |", "|---|---|---|"]
    out += [f"| {dll} | {len(fns)} | {', '.join(fns)} |" for dll, fns in sorted(imports.items())]
    callers = collections.defaultdict(set)
    for u in uses:
        callers[(u["iface"], u["method"])].add(u["addr"])
    for iface in sorted({k[0] for k in callers}):
        rows = sorted(((vtables.get(iface, {}).get(m, -1), m, sorted(a)) for (i, m), a in callers.items() if i == iface))
        out += ["", f"## {iface}: {len(rows)} of {len(vtables.get(iface, {}))} methods used", "",
                "| Slot | Method | Callers | Example callers |", "|---|---|---|---|"]
        for slot, m, addrs in rows:
            ex = ", ".join(f"`{names.get(a, a)}`" for a in addrs[:4])
            out.append(f"| {slot} | {m} | {len(addrs)} | {ex} |")
    out += ["", "## Full caller lists", ""]
    for (iface, m), addrs in sorted(callers.items()):
        out.append(f"- **{iface}::{m}** ({len(addrs)}): " + ", ".join(f"`{a}` {names.get(a, '')}" for a in sorted(addrs)))
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).parent))
    from nb11 import Nb11
    exe, export_dir, vt, out = map(Path, sys.argv[1:5])
    uses = [json.loads(l) for l in (export_dir / "vtable_uses.jsonl").read_text().splitlines() if l]
    names = {f["addr"]: f["name"] for f in map(json.loads, (export_dir / "functions.jsonl").read_text().splitlines()) if f}
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(Nb11.from_file(exe).imports(), uses, names, load_vtables(vt)))
    print("wrote", out)
