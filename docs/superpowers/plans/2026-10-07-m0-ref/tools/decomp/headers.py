"""Generate include/original/*.h from nb11 type lines (S/M records).

Every struct is emitted byte-exact for the original 32-bit layout: #pragma pack(1), members at their NB11
offsets with explicit uint8_t padding, tail padding to the NB11 size. Size/offset static_asserts are compiled
only for wasm32 (__wasm32__), where pointers are 4 bytes like the original; on 64-bit native the same headers
compile but are larger, which is why code must never memcpy file bytes into them (spec §4.1).
Overlapping members (unions, bitfields sharing a slot) keep the first member and list the rest in a comment.
All types live in namespace orig.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

PRIM_C = {"char": "char", "uchar": "unsigned char", "short": "int16_t", "ushort": "uint16_t", "long": "int32_t",
          "int": "int32_t", "ulong": "uint32_t", "uint": "uint32_t", "longlong": "int64_t", "ulonglong": "uint64_t",
          "float": "float", "double": "double", "bool": "bool", "wchar": "uint16_t", "void": "void"}
PRIM_BYTES = {"char": 1, "uchar": 1, "short": 2, "ushort": 2, "long": 4, "int": 4, "ulong": 4, "uint": 4,
              "longlong": 8, "ulonglong": 8, "float": 4, "double": 8, "bool": 1, "wchar": 2}


def ident(name: str) -> str:
    s = re.sub(r"[^A-Za-z0-9_]", "_", name)
    return "_" + s if s[:1].isdigit() else s


def parse(lines: list[str]) -> dict[str, dict]:
    structs, cur = {}, None
    for line in lines:
        if line.startswith("S "):
            _, name, size = line.split(" ")
            cur = structs.setdefault(ident(name), {"size": int(size), "members": []})
        elif line.startswith("M ") and cur is not None:
            _, off, tspec, size, name = line.split(" ", 4)
            cur["members"].append((int(off), tspec, int(size), ident(name)))
        elif line.startswith("F "):
            cur = None
    return structs


class Emitter:
    def __init__(self, structs: dict[str, dict]):
        self.structs = structs

    def ctype(self, tspec: str, size: int) -> tuple[str, str, set[str], set[str]]:
        """Return (type, array suffix, by-value deps, pointer deps)."""
        if tspec.startswith("ptr:"):
            inner = tspec[4:]
            if inner.startswith("struct:") and ident(inner[7:]) in self.structs:
                n = ident(inner[7:])
                return f"{n}*", "", set(), {n}
            if inner.startswith("prim:") and inner[5:] in PRIM_C:
                return PRIM_C[inner[5:]] + "*", "", set(), set()
            return "void*", "", set(), set()
        if tspec.startswith("prim:"):
            prim = tspec[5:]
            if PRIM_BYTES.get(prim) != size:  # void, long double, or a size NB11 disagrees with -> raw bytes
                return "uint8_t", f"[{size}]", set(), set()
            return PRIM_C[prim], "", set(), set()
        if tspec == "enum":
            return "uint32_t", "", set(), set()
        if tspec.startswith("struct:"):
            n = ident(tspec[7:])
            if n in self.structs and self.structs[n]["size"] == size:
                return n, "", {n}, set()
            return "uint8_t", f"[{size}]", set(), set()
        if tspec.startswith("arr:"):
            body, count = tspec[4:].rsplit(":", 1)
            count = int(count)
            if count and size % count == 0:
                t, suf, dv, dp = self.ctype(body, size // count)
                if not suf:
                    return t, f"[{count}]", dv, dp
            return "uint8_t", f"[{size}]", set(), set()
        return "uint8_t", f"[{size}]", set(), set()

    def emit(self, name: str) -> str:
        s = self.structs[name]
        body, deps_val, deps_ptr, skipped, asserts = [], set(), set(), [], []
        pos, seen = 0, set()
        for off, tspec, size, mname in sorted(s["members"], key=lambda m: m[0]):
            if size <= 0 or off < pos or off + size > s["size"]:
                skipped.append(f"{mname}@{off}")
                continue
            if off > pos:
                body.append(f"    uint8_t _pad_{pos:x}[{off - pos}];")
            t, suf, dv, dp = self.ctype(tspec, size)
            deps_val |= dv
            deps_ptr |= dp
            mn, k = mname, 2
            while mn in seen:
                mn, k = f"{mname}_{k}", k + 1
            seen.add(mn)
            body.append(f"    {t} {mn}{suf};")
            asserts.append(f"static_assert(offsetof({name}, {mn}) == {off}, \"{name}::{mn}\");")
            pos = off + size
        if pos < s["size"]:
            body.append(f"    uint8_t _pad_{pos:x}[{s['size'] - pos}];")
        if not body:
            body.append(f"    uint8_t _raw[{s['size']}];")
        out = ["// Generated by tools/decomp/headers.py from NB11 debug info. Do not edit.", "#pragma once",
               "#include <cstddef>", "#include <cstdint>"]
        out += [f'#include "{d}.h"' for d in sorted(deps_val - {name})]
        out += ["", "namespace orig {"]
        out += [f"struct {d};" for d in sorted(deps_ptr - deps_val - {name})]
        if skipped:
            out.append(f"// overlapping/unsized members not laid out: {', '.join(skipped)}")
        out += ["#pragma pack(push, 1)", f"struct {name} {{", *body, "};", "#pragma pack(pop)",
                "#if defined(__wasm32__)", f"static_assert(sizeof({name}) == {s['size']}, \"{name} size\");",
                *asserts, "#endif", "}  // namespace orig", ""]
        return "\n".join(out)


def generate(type_lines: list[str], out_dir: Path) -> int:
    structs = parse(type_lines)
    out_dir.mkdir(parents=True, exist_ok=True)
    em = Emitter(structs)
    for name in structs:
        (out_dir / f"{name}.h").write_text(em.emit(name))
    (out_dir / "all.cpp").write_text("".join(f'#include "{n}.h"\n' for n in sorted(structs)))
    return len(structs)


if __name__ == "__main__":
    lines = Path(sys.argv[1]).read_text().splitlines()
    print("headers", generate(lines, Path(sys.argv[2])))
